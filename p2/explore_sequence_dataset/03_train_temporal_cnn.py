"""
=============================================================================
Script 3: PyTorch Temporal CNN Training (Experiment A - 3 Features)
=============================================================================
Purpose:
    This script trains a 1D Convolutional Neural Network (Temporal CNN) to 
    classify dynamic hand gestures. It builds upon the baseline by expanding 
    the feature space and actively mitigating dataset imbalances.
    
    Key technical implementations:
    1) Feature Enrichment: Ingests 3 geometric features (Palm-Tilt, Temporal 
       Stability, and the newly re-introduced Z-axis Reach constraint) to give 
       the network richer spatial context over the 30-frame window.
    2) Video-Level Splitting: Uses GroupShuffleSplit to divide the train/test 
       sets by 'video_name', physically preventing data leakage.
    3) Class Weighting: Dynamically calculates and applies mathematical weights 
       to the CrossEntropyLoss function to heavily penalize errors on the 
       minority class ("Random" actions), preventing Majority Class Collapse.
    
Inputs:
    - 'experiment_a_baseline.csv': The processed dataset generated by Script 2,
      now containing 6 columns (metadata + 3 spatial features).
      
Outputs:
    - Console logs detailing Epoch Training/Validation Loss and Accuracy.
    - 'temporal_cnn_baseline.pth': The saved weights of the trained network.
=============================================================================
"""

import pandas as pd
import numpy as np
import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import Dataset, DataLoader
from sklearn.model_selection import GroupShuffleSplit
import os

# ==========================================
# 1. Hyperparameters & Settings
# ==========================================
WINDOW_SIZE = 30       # Number of frames per sequence (1 second at 30fps)
NUM_FEATURES = 3       # Tilt, Stability, and Z-Axis Reach
NUM_CLASSES = 2        # Handshake (1) vs. Random (0)
BATCH_SIZE = 16
EPOCHS = 25            # Slightly increased to allow the network to adjust to new weights
LEARNING_RATE = 0.001

# ==========================================
# 2. Sliding Window Generator
# ==========================================
def create_sliding_windows(df, window_size):
    """Slices continuous video rows into overlapping 3D tensors."""
    X, y, groups = [], [], []
    
    # Process each video completely independently
    for video_name, group in df.groupby('video_name'):
        features = group[['palm_tilt_degrees', 'temporal_stability', 'reach_z']].values
        label = group['label'].values[0] 
        
        # If a video is shorter than the window, skip it
        if len(features) >= window_size:
            # Slide the window down the video 1 frame at a time
            for i in range(len(features) - window_size + 1):
                X.append(features[i : i + window_size])
                y.append(label)
                groups.append(video_name) 
                
    return np.array(X), np.array(y), np.array(groups)

# ==========================================
# 3. PyTorch Dataset Class
# ==========================================
class HandshakeDataset(Dataset):
    def __init__(self, X, y):
        # PyTorch Conv1d expects shape: (Batch, Features, Sequence_Length)
        self.X = torch.tensor(X, dtype=torch.float32).transpose(1, 2)
        self.y = torch.tensor(y, dtype=torch.long)

    def __len__(self):
        return len(self.X)

    def __getitem__(self, idx):
        return self.X[idx], self.y[idx]

# ==========================================
# 4. Temporal CNN Architecture
# ==========================================
class TemporalCNN(nn.Module):
    def __init__(self, num_features, num_classes, window_size):
        super(TemporalCNN, self).__init__()
        
        self.conv_block = nn.Sequential(
            nn.Conv1d(in_channels=num_features, out_channels=16, kernel_size=5, padding=2),
            nn.ReLU(),
            nn.MaxPool1d(kernel_size=2),
            
            nn.Conv1d(in_channels=16, out_channels=32, kernel_size=3, padding=1),
            nn.ReLU(),
            nn.MaxPool1d(kernel_size=2)
        )
        
        # Calculate flattened dimension dynamically based on window size
        flattened_length = window_size // 4
        self.fc_input_size = 32 * flattened_length
        
        self.classifier = nn.Sequential(
            nn.Flatten(),
            nn.Linear(self.fc_input_size, 64),
            nn.ReLU(),
            nn.Dropout(0.5), # Regularization to prevent overfitting on small data
            nn.Linear(64, num_classes)
        )

    def forward(self, x):
        features = self.conv_block(x)
        return self.classifier(features)

# ==========================================
# 5. Main Execution & Training Loop
# ==========================================
if __name__ == "__main__":
    CSV_PATH = "experiment_a_baseline.csv"
    
    if not os.path.exists(CSV_PATH):
        print(f"ERROR: Cannot find {CSV_PATH}. Run Script 2 first!")
        exit()
        
    print("Loading data and generating sliding windows...")
    df = pd.read_csv(CSV_PATH)
    
    X_all, y_all, groups_all = create_sliding_windows(df, WINDOW_SIZE)
    print(f"Total sequences generated: {len(X_all)}")
    
    # Split by Video Group (80% Train, 20% Test)
    gss = GroupShuffleSplit(n_splits=1, train_size=0.8, random_state=42)
    train_idx, test_idx = next(gss.split(X_all, y_all, groups_all))
    
    X_train, y_train = X_all[train_idx], y_all[train_idx]
    X_test, y_test = X_all[test_idx], y_all[test_idx]
    
    print(f"Training on {len(np.unique(groups_all[train_idx]))} videos ({len(X_train)} windows)")
    print(f"Testing on {len(np.unique(groups_all[test_idx]))} videos ({len(X_test)} windows)\n")
    
    # Build DataLoaders
    train_loader = DataLoader(HandshakeDataset(X_train, y_train), batch_size=BATCH_SIZE, shuffle=True)
    test_loader = DataLoader(HandshakeDataset(X_test, y_test), batch_size=BATCH_SIZE, shuffle=False)
    
    model = TemporalCNN(NUM_FEATURES, NUM_CLASSES, WINDOW_SIZE)
    
    # --- ALGORITHMIC BALANCING: Class Weights ---
    # Calculate the frequency of each class in the training set
    class_counts = np.bincount(y_train)
    total_samples = len(y_train)
    
    # Math: (Total Samples) / (Number of Classes * Count of this Class)
    weights = total_samples / (len(class_counts) * class_counts)
    class_weights_tensor = torch.tensor(weights, dtype=torch.float32)
    
    print(f"Computed Class Weights: Class 0 (Random) = {weights[0]:.2f}, Class 1 (Handshake) = {weights[1]:.2f}\n")
    
    # Apply weights to the criterion
    criterion = nn.CrossEntropyLoss(weight=class_weights_tensor)
    optimizer = optim.Adam(model.parameters(), lr=LEARNING_RATE)
    
    print("Starting Training Loop...")
    for epoch in range(EPOCHS):
        model.train()
        train_loss, train_correct, train_total = 0.0, 0, 0
        
        for inputs, labels in train_loader:
            optimizer.zero_grad()
            outputs = model(inputs)
            loss = criterion(outputs, labels)
            loss.backward()
            optimizer.step()
            
            train_loss += loss.item()
            _, predicted = torch.max(outputs.data, 1)
            train_total += labels.size(0)
            train_correct += (predicted == labels).sum().item()
            
        train_acc = 100 * train_correct / train_total
        
        # Validation Phase
        model.eval()
        val_loss, val_correct, val_total = 0.0, 0, 0
        with torch.no_grad():
            for inputs, labels in test_loader:
                outputs = model(inputs)
                loss = criterion(outputs, labels)
                val_loss += loss.item()
                _, predicted = torch.max(outputs.data, 1)
                val_total += labels.size(0)
                val_correct += (predicted == labels).sum().item()
                
        val_acc = 100 * val_correct / val_total
        
        # Print metrics every 5 epochs and on the first epoch
        if (epoch + 1) % 5 == 0 or epoch == 0:
            print(f"Epoch [{epoch+1}/{EPOCHS}] | "
                  f"Train Loss: {train_loss/len(train_loader):.4f} - Acc: {train_acc:.2f}% | "
                  f"Val Loss: {val_loss/len(test_loader):.4f} - Acc: {val_acc:.2f}%")

    # Save the model
    torch.save(model.state_dict(), "temporal_cnn_baseline.pth")
    print("\nTraining Complete! Model weights saved as 'temporal_cnn_baseline.pth'.")
